unsafe extern "C" fn GenerateSyreen_generatePlanets(
    mut solarSys: *mut SOLARSYS_STATE,
) -> bool {
    GenerateDefault_generatePlanets(solarSys);
    (*solarSys).PlanetDesc[0usize].data_index = (C2Rust_Unnamed::WATER_WORLD.0
        as ::core::ffi::c_int | C2Rust_Unnamed::PLANET_SHIELDED.0 as ::core::ffi::c_int)
        as BYTE;
    (*solarSys).PlanetDesc[0usize].NumPlanets = 1 as BYTE;
    return true;
}
unsafe extern "C" fn GenerateSyreen_generateMoons(
    mut solarSys: *mut SOLARSYS_STATE,
    mut planet: *mut PLANET_DESC,
) -> bool {
    GenerateDefault_generateMoons(solarSys, planet);
    if matchWorld(solarSys, planet, 0 as BYTE, -1 as ::core::ffi::c_int as BYTE) {
        (*solarSys).MoonDesc[0usize].data_index = C2Rust_Unnamed::HIERARCHY_STARBASE.0
            as ::core::ffi::c_int as BYTE;
        (*solarSys).MoonDesc[0usize].radius = 35 as SIZE;
        (*solarSys).MoonDesc[0usize].location.x = (*(&raw mut sinetab as *mut SIZE)
            .offset(
                (((1 as ::core::ffi::c_int) << 6 as ::core::ffi::c_int
                    >> 2 as ::core::ffi::c_int)
                    + ((1 as ::core::ffi::c_int) << 6 as ::core::ffi::c_int
                        >> 2 as ::core::ffi::c_int)
                    & ((1 as ::core::ffi::c_int) << 6 as ::core::ffi::c_int)
                        - 1 as ::core::ffi::c_int) as COUNT as isize,
            ) as ::core::ffi::c_long
            * (*solarSys).MoonDesc[0usize].radius as ::core::ffi::c_long
            >> 14 as ::core::ffi::c_int) as SIZE as COORD;
        (*solarSys).MoonDesc[0usize].location.y = (*(&raw mut sinetab as *mut SIZE)
            .offset(
                ((1 as ::core::ffi::c_int) << 6 as ::core::ffi::c_int
                    >> 2 as ::core::ffi::c_int
                    & ((1 as ::core::ffi::c_int) << 6 as ::core::ffi::c_int)
                        - 1 as ::core::ffi::c_int) as COUNT as isize,
            ) as ::core::ffi::c_long
            * (*solarSys).MoonDesc[0usize].radius as ::core::ffi::c_long
            >> 14 as ::core::ffi::c_int) as SIZE as COORD;
    }
    return true;
}
unsafe extern "C" fn GenerateSyreen_generateOrbital(
    mut solarSys: *mut SOLARSYS_STATE,
    mut world: *mut PLANET_DESC,
) -> bool {
    if matchWorld(solarSys, world, 0 as BYTE, -1 as ::core::ffi::c_int as BYTE) {
        GenerateDefault_generateOrbital(solarSys, world);
        (*solarSys).SysInfo.PlanetInfo.SurfaceTemperature = 19 as SIZE;
        (*solarSys).SysInfo.PlanetInfo.Tectonics = 0 as UWORD;
        (*solarSys).SysInfo.PlanetInfo.Weather = 0 as UWORD;
        (*solarSys).SysInfo.PlanetInfo.AtmoDensity = (50 as ::core::ffi::c_int
            * 9 as ::core::ffi::c_int / 10 as ::core::ffi::c_int) as UWORD;
        return true;
    }
    if matchWorld(solarSys, world, 0 as BYTE, 0 as BYTE) {
        InitCommunication(CONVERSATION::SYREEN_CONVERSATION);
        return true;
    }
    GenerateDefault_generateOrbital(solarSys, world);
    return true;
}
